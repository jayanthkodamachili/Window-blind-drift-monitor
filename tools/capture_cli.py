"""Capture real CLI runs into a terminal-style SVG and a manifest.

A screenshot in a README is unfalsifiable: nobody can tell whether the numbers in the
picture came from the code. So the picture is generated here, from stdout captured at
generation time, and the manifest records each command with the exit code it actually
returned. A reader who doubts the image runs the command in the manifest.
"""

from __future__ import annotations

import json
import subprocess
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG_OUT = ROOT / "docs" / "cli-session.svg"
MANIFEST_OUT = ROOT / "docs" / "evidence-manifest.json"

COMMANDS = [
    # A real shift, found, on a window large enough to see it.
    [
        sys.executable, "-m", "drift_monitor.cli",
        "--detection-rows", "4000", "--n-features", "6", "--injected-shift", "0.3",
    ],
    # Silence that carries information: nothing fired, and something would have.
    [
        sys.executable, "-m", "drift_monitor.cli",
        "--detection-rows", "8000", "--n-features", "6",
        "--shifted-features", "0", "--material-shift", "0.5",
    ],
    # Silence that carries none: nothing fired, and nothing could have.
    [
        sys.executable, "-m", "drift_monitor.cli",
        "--detection-rows", "250", "--n-features", "6",
        "--shifted-features", "1", "--injected-shift", "0.06", "--material-shift", "0.06",
        "--power-replicates", "60", "--seed", "2",
    ],
    # A window too thin for its bins, refused where it is described.
    [
        sys.executable, "-m", "drift_monitor.cli",
        "--detection-rows", "100", "--psi-bins", "30",
    ],
]

BG = "#0f1117"
FG = "#d6dae2"
DIM = "#7d8795"
PROMPT = "#6ea8fe"
BAD = "#ff8f87"
OK = "#8bd98b"
LINE_H = 17
PAD = 16
CHAR_W = 7.22


def run_all() -> list[dict]:
    captured = []
    for command in COMMANDS:
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
        shown = " ".join(
            ["drift-monitor" if i < 3 else part for i, part in enumerate(command) if i >= 2]
        )
        captured.append(
            {
                "command": shown.replace("drift_monitor.cli", "drift-monitor"),
                "argv": command[2:],
                "exit_code": result.returncode,
                "stdout": result.stdout.rstrip("\n"),
                "stderr": result.stderr.rstrip("\n"),
            }
        )
    return captured


def to_svg(captured: list[dict]) -> str:
    lines: list[tuple[str, str]] = []
    for entry in captured:
        lines.append((f"$ {entry['command']}", PROMPT))
        for line in entry["stdout"].splitlines():
            lines.append((line, FG))
        for line in entry["stderr"].splitlines():
            lines.append((line, BAD))
        colour = OK if entry["exit_code"] in (0, 1, 4) else BAD
        lines.append((f"exit {entry['exit_code']}", colour))
        lines.append(("", FG))

    width = int(max(len(text) for text, _ in lines) * CHAR_W) + PAD * 2
    height = len(lines) * LINE_H + PAD * 2

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="Captured drift-monitor terminal session">',
        f'<rect width="{width}" height="{height}" rx="8" fill="{BG}"/>',
    ]
    for index, (text, colour) in enumerate(lines):
        y = PAD + 12 + index * LINE_H
        parts.append(
            f'<text x="{PAD}" y="{y}" font-family="SFMono-Regular,Consolas,monospace" '
            f'font-size="12" fill="{colour}" xml:space="preserve">{escape(text)}</text>'
        )
    parts.append(
        f'<text x="{PAD}" y="{height - 6}" font-family="SFMono-Regular,Consolas,monospace" '
        f'font-size="10" fill="{DIM}">generated by tools/capture_cli.py</text>'
    )
    parts.append("</svg>")
    return "".join(parts)


def main() -> int:
    captured = run_all()
    SVG_OUT.write_text(to_svg(captured) + "\n")
    MANIFEST_OUT.write_text(
        json.dumps(
            {
                "note": "each command was run by tools/capture_cli.py, exit codes as returned",
                "runs": [
                    {"command": c["command"], "exit_code": c["exit_code"]} for c in captured
                ],
            },
            indent=2,
        )
        + "\n"
    )
    for entry in captured:
        print(f"exit {entry['exit_code']}  {entry['command']}")
    print(f"wrote {SVG_OUT} and {MANIFEST_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
